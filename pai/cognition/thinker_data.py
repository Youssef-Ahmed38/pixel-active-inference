"""A common evidence window for the arm and maze HRM cause thinker.

Arm examples come from the already collected local v7 evidence, not Job C.
Maze examples are generated by the current visual/mobile simulator. The channels
retain a shared meaning: body motion, contact, focal entity, global scene,
vertical motion/force, and holding. Domain identity is an explicit context bit.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np

from pai.cognition.memory import CognitiveMemory
from pai.maze.advanced import run_advanced_episode
from pai.maze.env import MazeWorld

CAUSES = ("none", "push", "heavier_object", "slippery_object", "camera_shift",
          "passage_blocked", "unknown")
WINDOW = 20
FEATURES = ("body_motion", "contact", "focal_entity", "scene", "vertical_body",
            "vertical_force", "vertical_entity", "holding", "maze_domain")


@dataclass
class EvidenceSet:
    x: np.ndarray           # episodes x 20 x 9
    y: np.ndarray           # cause index
    teacher: np.ndarray     # episode x 7
    domain: np.ndarray      # arm or maze
    source: np.ndarray      # episode id / seed

    def __len__(self) -> int:
        return len(self.y)


def _window(x: np.ndarray, peak: int) -> np.ndarray:
    lo = max(0, peak - WINDOW + 5)
    selected = x[lo:lo + WINDOW]
    out = np.zeros((WINDOW, len(FEATURES)), np.float32)
    out[:len(selected)] = selected
    return out


def arm_evidence(path: str | Path) -> EvidenceSet:
    with np.load(path, allow_pickle=False) as file:
        arrays = {k: file[k] for k in file.files}
    rows, labels, teachers, sources = [], [], [], []
    for ep in range(len(arrays["labels"])):
        z = np.asarray(arrays["z"][arrays["episode"] == ep], np.float32)
        holding = np.asarray(arrays["holding"][arrays["episode"] == ep], np.float32)
        feat = np.stack([np.linalg.norm(z[:, :3], axis=1), np.linalg.norm(z[:, 3:6], axis=1),
                         np.linalg.norm(z[:, 6:9], axis=1), np.linalg.norm(z[:, 9:12], axis=1),
                         z[:, 2], z[:, 5], z[:, 8], holding, np.zeros(len(z))], axis=1)
        feat[:, :4] = np.arcsinh(feat[:, :4])
        feat[:, 4:7] = np.arcsinh(feat[:, 4:7])
        peak = int(np.argmax(0.5 * (z ** 2).sum(-1)))
        rows.append(_window(feat, peak))
        labels.append(CAUSES.index(str(arrays["labels"][ep])))
        posterior = np.zeros(len(CAUSES), np.float32)
        for old_i, name in enumerate(arrays["causes"]):
            posterior[CAUSES.index(str(name))] = arrays["teacher"][ep, old_i]
        teachers.append(posterior)
        sources.append(ep)
    return EvidenceSet(np.stack(rows), np.asarray(labels), np.stack(teachers),
                       np.repeat("arm", len(rows)), np.asarray(sources))


def maze_evidence(n_per_cause: int = 16, seed_start: int = 30000) -> EvidenceSet:
    rows, labels, teachers, sources = [], [], [], []
    modes = (("none", None, None), ("passage_blocked", 15, None),
             ("camera_shift", None, 15))
    for mode_i, (cause, block_at, shift_at) in enumerate(modes):
        accepted, attempts = 0, 0
        while accepted < n_per_cause:
            seed = seed_start + mode_i * 1000 + attempts
            attempts += 1
            if attempts > n_per_cause * 12:
                raise RuntimeError(f"could not generate {n_per_cause} {cause} maze episodes")
            memory = CognitiveMemory()
            world = MazeWorld(seed, size=11, sensor_range=2)
            result = run_advanced_episode(world, visual=True, mobile=True, budget=180,
                                          block_at=block_at, shift_at=shift_at,
                                          odom_noise=0.35, seed=seed, cognitive_memory=memory)
            if cause != "none" and cause not in result["truth_causes"]:
                continue
            ep = memory.episodes[0]
            feat = np.zeros((max(ep.steps + 1, 1), len(FEATURES)), np.float32)
            feat[:, -1] = 1.0
            for e in ep.evidence:
                if e.step >= len(feat) or not e.residual[0]:
                    continue
                if e.channels == ("unexpected_collision",):
                    feat[e.step, 0] = feat[e.step, 1] = 3.0
                elif e.channels == ("visual_frame_shift",):
                    feat[e.step, 3] = 3.0
            peak = int(np.argmax(feat[:, :4].sum(-1)))
            rows.append(_window(feat, peak))
            labels.append(CAUSES.index(cause))
            posterior = np.full(len(CAUSES), 0.002 / (len(CAUSES) - 1), np.float32)
            posterior[CAUSES.index(cause)] = 0.998
            teachers.append(posterior)
            sources.append(seed)
            accepted += 1
    return EvidenceSet(np.stack(rows), np.asarray(labels), np.stack(teachers),
                       np.repeat("maze", len(rows)), np.asarray(sources))


def combine(*sets: EvidenceSet) -> EvidenceSet:
    return EvidenceSet(*(np.concatenate([getattr(s, field) for s in sets])
                         for field in ("x", "y", "teacher", "domain", "source")))
